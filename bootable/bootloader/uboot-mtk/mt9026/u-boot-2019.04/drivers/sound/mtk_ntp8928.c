static int mtk_amp_i2c_write(struct udevice *dev, u8 reg, u8 *buf, u8 size)
{
	struct amp_ntp8928_priv *priv = dev_get_priv(dev);
	struct i2c_msg msgs;
	u8 msg_buf[10];
	int ret;
	int i;

	msg_buf[0] = reg;

	for (i = 1; i <= size; i++)
		msg_buf[i] = buf[i - 1];

	msgs.addr  = priv->i2c_addr;
	msgs.len   = size + 1;
	msgs.buf   = msg_buf;
	msgs.flags = I2C_M_STOP;

	ret = dm_i2c_xfer(dev, &msgs, 1);
	if (ret < 0)
		return ret;

	return 0;
}

static int amp_init(struct udevice *dev, unsigned char *inittable)
{
	u8 *pu8str = inittable;
	u8 *buf;
	u8 reg;
	u8 size;
	int ret;

	do {
		size = *pu8str;
		pu8str++;

		reg = *pu8str;
		pu8str++;

		buf = pu8str;
		ret = mtk_amp_i2c_write(dev, reg, buf, size);
		if (ret < 0) {
			dev_err(dev, "[AMP 8928]i2c write fail %d\n", ret);
			return -1;
		}

		pu8str = pu8str + size;
	} while (*pu8str != 0);

	return 0;
}

static int amp_ntp8928_reset(struct udevice *dev, bool enable)
{
	struct amp_ntp8928_priv *priv = dev_get_priv(dev);

	if (dm_gpio_is_valid(&priv->amp_reset))
		dm_gpio_set_value(&priv->amp_reset, enable);

	return 0;
}

static int amp_ntp8928_powerdown(struct udevice *dev, bool enable)
{
	struct amp_ntp8928_priv *priv = dev_get_priv(dev);

	if (dm_gpio_is_valid(&priv->amp_powerdown))
		dm_gpio_set_value(&priv->amp_powerdown, enable);

	return 0;
}

static int amp_ntp8928_set_params(struct udevice *dev, int interface, int rate,
				  int mclk_freq, int bits_per_sample, uint channels)
{
	int ret;

	amp_ntp8928_powerdown(dev, 0);
	//pull down amp PD pin
	amp_ntp8928_reset(dev, 0);
	//wait t2 min time = 10ms
	mdelay(10);
	//pull up amp PD pin
	amp_ntp8928_reset(dev, 1);
	//wait t3 min time = 5ms
	mdelay(5);
	//pull up amp PD pin
	amp_ntp8928_reset(dev, 0);
	//wait t4 min time = 1ms
	mdelay(1);

	ret = amp_init(dev, ampinittblntp8928);
	if (ret < 0) {
		dev_err(dev, "[AMP 8928]Unable to init AMP NTP8928\n");
		return -EINVAL;
	}

	return 0;
}

static int amp_ntp8928_probe(struct udevice *dev)
{
	struct amp_ntp8928_priv *priv = dev_get_priv(dev);
	int ret;

	if (dev_read_enabled(dev) == 0)
		return 0;

	if (device_get_uclass_id(dev->parent) != UCLASS_I2C) {
		dev_err(dev, "[AMP 8928]get i2c parent fail\n");
		return -EPROTONOSUPPORT;
	}

	ret = dev_read_u32(dev, "reg", &priv->i2c_addr);
	if (ret) {
		dev_err(dev, "[AMP 8928]can't get slave addr\n");
		return -EINVAL;
	}

	ret = gpio_request_by_name(dev, "amppowerdown-gpios", 0, &priv->amp_powerdown, GPIOD_IS_OUT);
	if (ret) {
		dev_err(dev, "[AMP 8928]get amp powerdown gpio fail %d\n", ret);
		return -EINVAL;
	}

	ret = gpio_request_by_name(dev, "ampreset-gpios", 0, &priv->amp_reset, GPIOD_IS_OUT);
	if (ret) {
		dev_err(dev, "[AMP 8928]get amp reset gpio fail %d\n", ret);
		return -EINVAL;
	}

	return 0;
}

